"""Regenerate the academic frontend ZIP from its actual eight-example source.

create_demo_pdfs.py builds the four OCR validation fixtures; the eight-example
frontend package is generated by academic_examples.py. Keep these sources distinct.
"""
import argparse
from pathlib import Path
import tempfile
import zipfile
import pymupdf
from scripts.academic_examples import write_examples


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', required=True)
    output = Path(parser.parse_args().output)
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as temporary:
        folder = Path(temporary)
        examples = write_examples(folder)
        assert len(examples) == 8
        for name, content in examples.items():
            # The low-resolution fixture is a rasterized fictional source.
            if name.startswith('04-'):
                continue
            with pymupdf.open(stream=content, filetype='pdf') as pdf:
                assert all('EXPEDIENTE FICTICIO' in page.get_text() for page in pdf)
        with zipfile.ZipFile(output, 'w', zipfile.ZIP_DEFLATED) as archive:
            for path in sorted(folder.iterdir()):
                archive.write(path, path.name)
    print('Generated eight fictional examples; no citizen documents included.')


if __name__ == '__main__':
    main()
